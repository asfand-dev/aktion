/** `todo-row.aktion` → `todo-row.d.aktion.ts`, the name TypeScript looks up for `./todo-row.aktion`. */
export function declarationFileName(modulePath: string): string {
  return modulePath.replace(/\.aktion$/i, ".d.aktion.ts");
}

/** Names TypeScript does not accept as a binding (a parameter or a declared const). */
const RESERVED_WORDS = new Set(
  (
    "break case catch class const continue debugger default delete do else enum export extends false finally for " +
    "function if implements import in instanceof interface let new null package private protected public return " +
    "static super switch this throw true try typeof var void while with yield await"
  ).split(" "),
);

const IDENTIFIER = /^[A-Za-z_$][\w$]*$/;

/** A property name as written in a type literal: bare when it is an identifier, quoted otherwise. */
const propertyName = (key: string): string => (IDENTIFIER.test(key) ? key : JSON.stringify(key));

/** One exported binding of a module: its TypeScript name, and the lines that declare it. */
interface Declared {
  name: string;
  lines: string[];
  /** `aktion-runtime/dsl` types the lines mention. */
  uses: Set<string>;
}

/**
 * The names an Aktion module exports, as host code would import them: `$count`
 * for an atom or hook, `TodoRow` for a component, action or plain binding. A
 * later top-level declaration of a name replaces an earlier one, as it does at
 * runtime.
 */
export function aktionExportNames(program: Program): string[] {
  const names = new Set<string>();
  const listed = listedExports(program);
  for (const stmt of program.statements) {
    for (const name of exportNames(stmt, listed)) names.add(name);
    if (stmt.kind === "ExportList" && stmt.source !== undefined) {
      for (const spec of stmt.specifiers) names.add(spec.isState ? `$${spec.exported}` : spec.exported);
    }
  }
  return [...names];
}

/** The binding key of a declaration — `$count` for an atom or hook, `TodoRow` otherwise — or `null` for a statement that declares none. */
function declaredKey(stmt: Statement): string | null {
  switch (stmt.kind) {
    case "ComponentDeclaration":
    case "ActionDeclaration":
      return stmt.name;
    case "HookDeclaration":
      return `$${stmt.name}`;
    case "Assignment":
      return stmt.isState ? `$${stmt.identifier}` : stmt.identifier;
    default:
      return null;
  }
}

/** Local binding key → the names an `export { … }` list gives it (no `from`; those are forwarded as written). */
function listedExports(program: Program): Map<string, string[]> {
  const listed = new Map<string, string[]>();
  for (const stmt of program.statements) {
    if (stmt.kind !== "ExportList" || stmt.source !== undefined) continue;
    for (const spec of stmt.specifiers) {
      const key = spec.isState ? `$${spec.local}` : spec.local;
      listed.set(key, [...(listed.get(key) ?? []), spec.isState ? `$${spec.exported}` : spec.exported]);
    }
  }
  return listed;
}

/** The names a statement is exported under: its own, when it carries `export`, plus every `export { … }` entry for it. */
function exportNames(stmt: Statement, listed: ReadonlyMap<string, string[]>): string[] {
  const key = declaredKey(stmt);
  if (key === null) return [];
  const own = "exported" in stmt && stmt.exported ? [key] : [];
  return [...new Set([...own, ...(listed.get(key) ?? [])])];
}

/** The declaration text for one `.aktion` module, and the parse errors it had. */
export function aktionDeclarationText(
  source: string,
  sourceName = "module.aktion",
): { text: string; errors: ParseError[] } {
  const program = parse(source);
  const assigned = assignedValues(program);
  // Local (non-exported) names the declarations introduce must not collide
  // with an export — nor with each other.
  const taken = new Set(aktionExportNames(program));
  // Last declaration of a name wins, as top-level re-binding does at runtime —
  // two declarations of one name would be TS2451 / TS2300.
  const byName = new Map<string, Declared>();
  const listed = listedExports(program);
  for (const stmt of program.statements) {
    for (const name of exportNames(stmt, listed)) {
      const declared = declare(stmt, name, assigned, taken);
      if (declared === null) continue;
      byName.delete(declared.name);
      byName.set(declared.name, declared);
    }
  }
  // A re-export is declared by pointing at the other module's own declaration
  // file, which TypeScript finds through `allowArbitraryExtensions`.
  const forwarded: string[] = [];
  for (const stmt of program.statements) {
    if (stmt.kind !== "ExportList" || stmt.source === undefined) continue;
    if (stmt.all) {
      forwarded.push(`export * from ${JSON.stringify(stmt.source)};`);
      continue;
    }
    const specs = stmt.specifiers.map((s) => {
      const local = s.isState ? `$${s.local}` : s.local;
      return s.exported === s.local ? local : `${local} as ${s.isState ? `$${s.exported}` : s.exported}`;
    });
    forwarded.push(`export { ${specs.join(", ")} } from ${JSON.stringify(stmt.source)};`);
  }

  const uses = new Set<string>(["CompiledProgram"]);
  const lines: string[] = [];
  for (const declared of byName.values()) {
    for (const type of declared.uses) uses.add(type);
    lines.push(...declared.lines);
  }
  const local = unusedName("compiled", taken);

  const text = [
    `${DECLARATION_HEADER} from ${sourceName} — do not edit.`,
    `import type { ${[...uses].sort().join(", ")} } from "aktion-runtime/dsl";`,
    "",
    ...lines,
    ...forwarded,
    ...(lines.length + forwarded.length > 0 ? [""] : []),
    `declare const ${local}: CompiledProgram;`,
    `export default ${local};`,
    "",
  ].join("\n");
  return { text, errors: program.errors };
}

function declare(
  stmt: Statement,
  name: string,
  assigned: ReadonlyMap<string, Written[]>,
  taken: Set<string>,
): Declared | null {
  const uses = new Set<string>();
  switch (stmt.kind) {
    case "ComponentDeclaration":
      return { name, lines: componentOverloads(name, stmt.params, uses, stmt.name), uses };
    case "ActionDeclaration":
    case "HookDeclaration":
      return { name, lines: [`export declare function ${name}(${parameterList(stmt.params)}): any;`], uses };
    case "Assignment": {
      const mutable = stmt.isState || stmt.declaration === "let" || stmt.declaration === "var";
      const type = mutable ? bindingType(stmt.expression, assigned.get(declaredKey(stmt)!) ?? [], uses) : valueType(stmt.expression, uses);
      return { name, lines: exportBinding(name, mutable ? "let" : "const", type, taken), uses };
    }
    default:
      return null;
  }
}

/** `base`, or `_base`, `__base`, … — the first not in `taken`, which it is then added to. */
function unusedName(base: string, taken: Set<string>): string {
  let name = base;
  while (taken.has(name) || RESERVED_WORDS.has(name)) name = `_${name}`;
  taken.add(name);
  return name;
}

/** `export declare let name: T;` — through a local alias when `name` is a reserved word (`export class = 1`). */
function exportBinding(name: string, keyword: "let" | "const", type: string, taken: Set<string>): string[] {
  if (!RESERVED_WORDS.has(name)) return [`export declare ${keyword} ${name}: ${type};`];
  const local = unusedName(name, taken);
  return [`declare ${keyword} ${local}: ${type};`, `export { ${local} as ${name} };`];
}

/* ---- parameters ---- */

/**
 * The name each parameter is declared under: its own, or `p{i}` for a
 * destructuring pattern — made unique against the real names, so
 * `({ a }, p0)` does not declare `p0` twice — and `_`-prefixed when TypeScript
 * reserves it.
 */
function parameterNames(params: ReadonlyArray<DeclParam>): string[] {
  const taken = new Set(params.map((p) => p.name).filter((n) => n !== ""));
  return params.map((p, i) => {
    let name = p.name || `p${i}`;
    if (p.name !== "" && !RESERVED_WORDS.has(name)) return name;
    while (taken.has(name) || RESERVED_WORDS.has(name)) name = `_${name}`;
    taken.add(name);
    return name;
  });
}

/**
 * A parameter's type: the primitive of a literal default plus `null` (only
 * `undefined` selects the default; `null` is bound as passed), `any` for
 * everything else. Object and array defaults stay `any`: an object literal
 * passed in their place is checked for excess properties, which the runtime
 * never rejects.
 */
function parameterType(param: DeclParam): string {
  if (param.pattern || !param.defaultValue) return "any";
  const type = valueType(param.defaultValue, new Set());
  return type === "string" || type === "number" || type === "boolean" ? `${type} | null` : "any";
}

/** `T | undefined` — the type of an optional parameter given in a position that must be filled. */
const optionalType = (type: string): string => (type === "any" ? "any" : `${type} | undefined`);

/** One optional parameter per declared one, so arity is checked; a rest parameter as `...name: any[]`. */
function parameterList(params: ReadonlyArray<DeclParam>): string {
  const names = parameterNames(params);
  return params.map((p, i) => (p.rest ? `...${names[i]}: any[]` : `${names[i]}?: ${parameterType(p)}`)).join(", ");
}

/**
 * The overloads of a component, mirroring how `invokeComponentDecl` binds a
 * call. The named props are the RIGHTMOST object literal, and only when one of
 * its keys is `key` or a parameter's name — or every parameter is already
 * filled positionally, which makes its keys named slots. Every other argument
 * is positional, wherever it stands: the positionals fill the parameters in
 * order, before the props or after them, and those past the last parameter are
 * `children`. So:
 *
 *   1. positional: each parameter, then extra positionals as `children`;
 *   2. for each count `m` of parameters filled positionally, and each split of
 *      those `m` around the props (`k` before, `m - k` after): props that name
 *      `key` or one of the parameters not filled (a parameter given positionally
 *      AND by name loses the positional value, so the props may not name it);
 *      children follow only once `m` fills every parameter;
 *   3. every parameter, children, and the props last.
 *
 * Any other key of the props is a named slot (`slots.header`), hence the index
 * signature. Types cannot tell an object literal from an object value, which
 * leaves two calls accepted as the wrong binding: props in a position whose
 * parameter is `any` read as that parameter (`Pill({ key: 1 }, "h", 42)` binds
 * `label: "h", tone: 42`), and a literal positional after the props is the
 * rightmost literal itself, and takes their place. A component with a rest
 * parameter keeps a single permissive positional form: the runtime binds its
 * rest parameter to one value.
 */
function componentOverloads(name: string, params: ReadonlyArray<DeclParam>, uses: Set<string>, tag = name): string[] {
  uses.add("AktionNode");
  const result = `AktionNode<${JSON.stringify(tag)}>`;
  const names = parameterNames(params);
  const types = params.map(parameterType);
  if (params.some((p) => p.rest)) {
    const list = params.map((p, i) => (p.rest ? `...${names[i]}: any[]` : `${names[i]}?: ${types[i]}`)).join(", ");
    return [`export declare function ${name}(${list}): ${result};`];
  }
  uses.add("Children");
  uses.add("Key");

  // The overloads' own parameter names must not repeat a real one (TS2300).
  let children = "children";
  while (names.includes(children)) children = `_${children}`;
  let propsName = "props";
  while (names.includes(propsName) || propsName === children) propsName = `_${propsName}`;
  const rest = `...${children}: Children[]`;
  // The name a caller uses for each parameter; a pattern has none, and a
  // parameter named `key` is unreachable by name (`key` is the identity).
  const keys = params.map((p) => (p.pattern || (p.publicName ?? p.name) === "key" ? null : (p.publicName ?? p.name)));
  const props = `${name}Props`;
  /** Parameters `from`..`to - 1`, each given positionally (possibly as `undefined`). */
  const given = (from: number, to: number): string[] =>
    names.slice(from, to).map((n, i) => `${n}: ${optionalType(types[from + i]!)}`);
  /** The props when the first `m` parameters are filled positionally. */
  const bag = (m: number): string => {
    const parts = [props];
    const repeated = keys.slice(0, m).filter((key): key is string => key !== null);
    if (repeated.length > 0) parts.push(`{ ${repeated.map((key) => `readonly ${propertyName(key)}?: never`).join("; ")} }`);
    if (m < params.length) {
      const members = ["{ readonly key: Key }"];
      for (let i = m; i < params.length; i += 1) {
        const key = keys[i];
        if (key !== null && key !== undefined) members.push(`{ readonly ${propertyName(key)}: ${optionalType(types[i]!)} }`);
      }
      parts.push(members.length === 1 ? members[0]! : `(${members.join(" | ")})`);
    }
    return parts.join(" & ");
  };

  const lines = [
    `/** Named props of \`${name}\`: its parameters by name, \`key\`, and named slots (any other key). */`,
    `export interface ${props} {`,
    "  readonly key?: Key;",
    ...keys.flatMap((key, i) => (key === null ? [] : [`  readonly ${propertyName(key)}?: ${types[i]};`])),
    "  readonly [slot: string]: unknown;",
    "}",
    `export declare function ${name}(${[...names.map((n, i) => `${n}?: ${types[i]}`), rest].join(", ")}): ${result};`,
  ];
  for (let m = 0; m <= params.length; m += 1) {
    for (let k = 0; k <= m; k += 1) {
      const list = [...given(0, k), `${propsName}: ${bag(m)}`, ...given(k, m)];
      if (m === params.length) list.push(rest);
      lines.push(`export declare function ${name}(${list.join(", ")}): ${result};`);
    }
  }
  lines.push(
    `export declare function ${name}(...args: [${[...given(0, params.length), rest, `${propsName}: ${bag(params.length)}`].join(", ")}]): ${result};`,
  );
  return lines;
}

