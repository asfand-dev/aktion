/** A glob (`src/**\/*.aktion`) as an anchored RegExp over `/`-separated relative paths. */
function globToRegExp(glob: string): RegExp {
  let re = "";
  for (let i = 0; i < glob.length; i += 1) {
    const ch = glob[i]!;
    if (ch === "*") {
      if (glob[i + 1] === "*") {
        const slash = glob[i + 2] === "/";
        re += slash ? "(?:.*/)?" : ".*";
        i += slash ? 2 : 1;
      } else {
        re += "[^/]*";
      }
    } else if (ch === "?") {
      re += "[^/]";
    } else {
      re += /[\\^$.|+()[\]{}]/.test(ch) ? `\\${ch}` : ch;
    }
  }
  return new RegExp(`^${re}$`);
}

const toPosix = (p: string): string => p.split(sep).join("/");

function walkFiles(dir: string, skip: ReadonlySet<string>, out: string[]): void {
  let entries: string[];
  try {
    entries = readdirSync(dir);
  } catch {
    return;
  }
  for (const name of entries) {
    const full = join(dir, name);
    if (skip.has(full)) continue;
    let stats;
    try {
      stats = statSync(full);
    } catch {
      continue;
    }
    if (stats.isDirectory()) {
      if (!SKIPPED_DIRECTORIES.has(name)) walkFiles(full, skip, out);
    } else if (stats.isFile()) {
      out.push(full);
    }
  }
}

interface Resolved {
  root: string;
  outDir: string;
  include: RegExp[];
  exclude: RegExp[];
  write: boolean;
}

function resolveOptions(options: AktionDeclarationsOptions): Resolved {
  const root = resolve(options.root ?? process.cwd());
  return {
    root,
    outDir: resolve(root, options.outDir ?? DEFAULT_DECLARATIONS_DIR),
    include: (options.include ?? ["src/**/*.aktion"]).map(globToRegExp),
    exclude: (options.exclude ?? []).map(globToRegExp),
    write: options.write !== false,
  };
}

function isDeclared(file: string, o: Resolved): boolean {
  if (!/\.aktion$/i.test(file)) return false;
  const rel = toPosix(relative(o.root, file));
  if (rel.startsWith("..")) return false;
  return o.include.some((re) => re.test(rel)) && !o.exclude.some((re) => re.test(rel));
}

function targetOf(file: string, o: Resolved): string {
  return join(o.outDir, declarationFileName(relative(o.root, file)));
}

function emitOne(file: string, o: Resolved, result: AktionDeclarationsResult): string {
  const target = targetOf(file, o);
  const { text, errors } = aktionDeclarationText(readFileSync(file, "utf8"), toPosix(relative(o.root, file)));
  for (const e of errors) result.diagnostics.push({ path: file, line: e.line, column: e.column, message: e.message });
  const current = existsSync(target) ? readFileSync(target, "utf8") : null;
  if (current === text) {
    result.unchanged.push(target);
  } else {
    result.written.push(target);
    if (o.write) {
      mkdirSync(dirname(target), { recursive: true });
      writeFileSync(target, text);
    }
  }
  return target;
}

/**
 * Write a `name.d.aktion.ts` declaration for every `.aktion` module under
 * `root` that `include` matches — only where the text changed, so a watcher
 * does not fire for nothing — and remove generated declarations whose module
 * is gone.
 */
export function emitAktionDeclarations(options: AktionDeclarationsOptions = {}): AktionDeclarationsResult {
  const o = resolveOptions(options);
  const result: AktionDeclarationsResult = { written: [], unchanged: [], removed: [], diagnostics: [] };
  const files: string[] = [];
  walkFiles(o.root, new Set([o.outDir]), files);
  const targets = new Set<string>();
  for (const file of files.sort()) if (isDeclared(file, o)) targets.add(emitOne(file, o, result));

  // Stale declarations: generated by us (the header says so), module gone.
  const existing: string[] = [];
  walkFiles(o.outDir === o.root ? o.root : o.outDir, new Set(), existing);
  for (const file of existing) {
    if (!file.endsWith(".d.aktion.ts") || targets.has(file)) continue;
    let head = "";
    try {
      head = readFileSync(file, "utf8").slice(0, DECLARATION_HEADER.length);
    } catch {
      continue;
    }
    if (head !== DECLARATION_HEADER) continue;
    result.removed.push(file);
    if (o.write) rmSync(file, { force: true });
  }
  return result;
}

/**
 * Bring one module's declaration up to date — after an edit, or remove it
 * after a deletion. Used by the Vite plugin's dev server; a module `include`
 * does not match is ignored.
 */
export function updateAktionDeclaration(file: string, options: AktionDeclarationsOptions = {}): AktionDeclarationsResult {
  const o = resolveOptions(options);
  const result: AktionDeclarationsResult = { written: [], unchanged: [], removed: [], diagnostics: [] };
  const absolute = resolve(file);
  if (!isDeclared(absolute, o)) return result;
  if (existsSync(absolute)) {
    emitOne(absolute, o, result);
  } else {
    const target = targetOf(absolute, o);
    if (existsSync(target)) {
      result.removed.push(target);
      if (o.write) rmSync(target, { force: true });
    }
  }
  return result;
}
