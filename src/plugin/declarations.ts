/**
 * Type declarations for `.aktion` modules, so `.aktion.ts` code can import from
 * them with types (guide §7.10).
 *
 * TypeScript knows nothing about `.aktion` files: `import { TodoRow } from
 * "./todo-row.aktion"` fails with TS2614 against the ambient `*.aktion`
 * wildcard. With `allowArbitraryExtensions`, TypeScript resolves that import to
 * a sibling `todo-row.d.aktion.ts` first — so this module writes one per
 * `.aktion` file, declaring what it exports:
 *
 *   - a component as a function of optional `any` parameters plus `...rest`
 *     (components also take a trailing named-props object and extra children);
 *   - an action with one optional `any` per parameter, so arity is checked;
 *   - a hook as `(...args: any[]) => any`;
 *   - an atom or plain binding with the primitive type of a literal
 *     initializer, `any` otherwise;
 *   - always a default export typed as the `CompiledProgram` the Vite plugin
 *     produces, so `import app from "./app.aktion"` stays typed.
 *
 * The declarations can live outside the source tree: with the default `outDir`
 * (`.aktion-types`), add `"rootDirs": ["src", ".aktion-types/src"]` to the
 * tsconfig. `.aktion.js` / `.aktion.ts` modules need no declarations — with
 * `allowJs`, TypeScript reads them directly.
 *
 * Node-only (it reads and writes files).
 */

import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { parse } from "../parser/index.js";
import type { DeclParam, Expression, ParseError, Statement } from "../parser/types.js";

/** First line of every generated file — how stale ones are recognised and removed. */
export const DECLARATION_HEADER = "// Generated by aktion-dts";

/** Where declarations go by default, relative to `root`. */
export const DEFAULT_DECLARATIONS_DIR = ".aktion-types";

/** Directories never searched for `.aktion` modules. */
const SKIPPED_DIRECTORIES = new Set(["node_modules", ".git", "dist"]);

export interface AktionDeclarationsOptions {
  /** Project root; `include`, `exclude` and `outDir` are relative to it. Default: `process.cwd()`. */
  root?: string;
  /** Globs of `.aktion` modules to declare. Default: `["src/**\/*.aktion"]`. */
  include?: string[];
  /** Globs to leave out. */
  exclude?: string[];
  /**
   * Directory the declarations are written to, mirroring the modules' paths.
   * Default: `.aktion-types`. Pass the root itself (`"."`) to write each one
   * next to its module.
   */
  outDir?: string;
  /** `false` computes the result without touching the disk (`aktion-dts --check`). Default: true. */
  write?: boolean;
}

export interface AktionDeclarationsResult {
  /** Declarations created or changed (or that would be, with `write: false`). */
  written: string[];
  /** Declarations already up to date. */
  unchanged: string[];
  /** Generated declarations whose module no longer exists, removed. */
  removed: string[];
  /** Parse errors of the modules (declared as far as they parsed). */
  diagnostics: Array<{ path: string; line: number; column: number; message: string }>;
}

/* -------------------------------------------------------------------------- */
/*  One module                                                                 */
/* -------------------------------------------------------------------------- */

/** `todo-row.aktion` → `todo-row.d.aktion.ts`, the name TypeScript looks up for `./todo-row.aktion`. */
export function declarationFileName(modulePath: string): string {
  return modulePath.replace(/\.aktion$/i, ".d.aktion.ts");
}

/** The declaration text for one `.aktion` module, and the parse errors it had. */
export function aktionDeclarationText(
  source: string,
  sourceName = "module.aktion",
): { text: string; errors: ParseError[] } {
  const program = parse(source);
  const lines: string[] = [];
  let usesNode = false;
  for (const stmt of program.statements) {
    const line = declare(stmt);
    if (line === null) continue;
    if (line.includes("AktionNode")) usesNode = true;
    lines.push(line);
  }
  const types = usesNode ? "AktionNode, CompiledProgram" : "CompiledProgram";
  const text = [
    `${DECLARATION_HEADER} from ${sourceName} — do not edit.`,
    `import type { ${types} } from "aktion-runtime/dsl";`,
    "",
    ...lines,
    ...(lines.length > 0 ? [""] : []),
    "declare const compiled: CompiledProgram;",
    "export default compiled;",
    "",
  ].join("\n");
  return { text, errors: program.errors };
}

function declare(stmt: Statement): string | null {
  switch (stmt.kind) {
    case "ComponentDeclaration":
      if (!stmt.exported) return null;
      return `export declare function ${stmt.name}(${parameters(stmt.params, true)}): AktionNode;`;
    case "ActionDeclaration":
      if (!stmt.exported) return null;
      return `export declare function ${stmt.name}(${parameters(stmt.params, false)}): any;`;
    case "HookDeclaration":
      if (!stmt.exported) return null;
      return `export declare function $${stmt.name}(...args: any[]): any;`;
    case "Assignment": {
      if (!stmt.exported) return null;
      if (stmt.isState) return `export declare let $${stmt.identifier}: ${valueType(stmt.expression)};`;
      const keyword = stmt.declaration === "let" || stmt.declaration === "var" ? "let" : "const";
      return `export declare ${keyword} ${stmt.identifier}: ${valueType(stmt.expression)};`;
    }
    default:
      return null;
  }
}

/** One optional `any` per declared parameter (`p{i}` for a pattern), a rest parameter as `...name: any[]`. */
function parameters(params: ReadonlyArray<DeclParam>, component: boolean): string {
  const names = new Set<string>();
  const out = params.map((p, i) => {
    const name = p.name || `p${i}`;
    names.add(name);
    return p.rest ? `...${name}: any[]` : `${name}?: any`;
  });
  // Components also take a trailing named-props object and extra children.
  if (component && !params.some((p) => p.rest)) {
    let rest = "rest";
    while (names.has(rest)) rest = `_${rest}`;
    out.push(`...${rest}: any[]`);
  }
  return out.join(", ");
}

/** The primitive type of a literal initializer; `any` for everything else. */
function valueType(expr: Expression): string {
  switch (expr.kind) {
    case "Literal":
      return typeof expr.value === "string" || typeof expr.value === "number" || typeof expr.value === "boolean"
        ? typeof expr.value
        : "any";
    case "Template":
      return "string";
    case "Unary":
      if ((expr.operator === "-" || expr.operator === "+") && expr.argument.kind === "Literal" && typeof expr.argument.value === "number") {
        return "number";
      }
      return expr.operator === "!" ? "boolean" : "any";
    case "Lambda":
      return "(...args: any[]) => any";
    default:
      return "any";
  }
}

