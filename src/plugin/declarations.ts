/** Resource builtins and the `aktion-runtime/dsl` type of the handle each returns. */
const RESOURCE_TYPES: Readonly<Record<string, string>> = {
  http: "HttpResource",
  mutation: "MutationResource",
  socket: "SocketResource",
  sse: "SseResource",
  script: "ScriptResource",
};

const PRIMITIVES = new Set(["string", "number", "boolean"]);

/** A function type inside a union or an array needs parentheses. */
const grouped = (type: string): string => (type.startsWith("(") && type.includes("=>") ? `(${type})` : type);

/**
 * The type of an expression whose type the source states — a literal, a
 * template, an array or object literal, a resource factory — and `any` for
 * everything else. `null` is `"null"`; callers decide what it widens.
 */
function valueType(expr: Expression, uses: Set<string>): string {
  switch (expr.kind) {
    case "Literal":
      if (expr.value === null) return "null";
      return typeof expr.value === "string" || typeof expr.value === "number" || typeof expr.value === "boolean"
        ? typeof expr.value
        : "any";
    case "Template":
      return "string";
    case "Unary":
      if ((expr.operator === "-" || expr.operator === "+") && expr.argument.kind === "Literal" && typeof expr.argument.value === "number") {
        return "number";
      }
      return expr.operator === "!" ? "boolean" : "any";
    case "Lambda":
      return "(...args: any[]) => any";
    case "Array":
      return arrayType([expr], uses);
    case "Object":
      return isShape(expr) ? objectType([expr], uses) : "any";
    case "Invoke":
      return expr.callee.kind === "StateRef" ? resourceType(expr.callee.name, expr.arguments, uses) : "any";
    default:
      return "any";
  }
}

/** An object literal whose keys the source states: no spread, no computed key. */
const isShape = (expr: ObjectExpr): boolean => expr.properties.every((p) => !p.spread && !p.computedKey);

/**
 * The types a value can have when it is one of `exprs`, in source order. Object
 * literals merge into one shape and array literals into one array, so
 * `[{ id: 1 }, { id: 2, done: true }]` reads as `{ id: number; done?: boolean }`
 * — a union of the two would reject `t.done`, which the runtime reads as
 * `undefined` or `true`.
 */
function unionTypes(exprs: readonly Expression[], uses: Set<string>): string[] {
  const objects: ObjectExpr[] = [];
  const arrays: ArrayExpr[] = [];
  // Each list stands where its first literal does, for the merged type.
  const slots: Array<string | ObjectExpr[] | ArrayExpr[]> = [];
  for (const expr of exprs) {
    if (expr.kind === "Object" && isShape(expr)) {
      if (objects.length === 0) slots.push(objects);
      objects.push(expr);
    } else if (expr.kind === "Array") {
      if (arrays.length === 0) slots.push(arrays);
      arrays.push(expr);
    } else {
      slots.push(valueType(expr, uses));
    }
  }
  const types = slots.map((slot) =>
    typeof slot === "string" ? slot : slot === objects ? objectType(objects, uses) : arrayType(arrays, uses),
  );
  return [...new Set(types)];
}

/** One array type for every element of `arrays`; `any[]` when one is empty or spreads, or an element is unknown. */
function arrayType(arrays: readonly ArrayExpr[], uses: Set<string>): string {
  const elements = arrays.flatMap((a) => a.elements);
  if (arrays.some((a) => a.elements.length === 0) || elements.some((e) => e.kind === "Spread")) return "any[]";
  const union = unionTypes(elements, uses);
  if (union.includes("any")) return "any[]";
  return union.length === 1 && IDENTIFIER.test(union[0]!) ? `${union[0]}[]` : `Array<${union.map(grouped).join(" | ")}>`;
}

/**
 * One object type for every literal in `objects`: each key typed by all its
 * values, and optional where some literal lacks it. A key that is only ever
 * `null` is `any` — a placeholder whose real type the source does not state.
 */
function objectType(objects: readonly ObjectExpr[], uses: Set<string>): string {
  const values = new Map<string, Expression[]>();
  for (const obj of objects) {
    for (const prop of obj.properties) {
      const list = values.get(prop.key) ?? [];
      list.push(prop.value);
      values.set(prop.key, list);
    }
  }
  if (values.size === 0) return "Record<string, any>";
  const fields: string[] = [];
  for (const [key, exprs] of values) {
    const optional = objects.some((obj) => !obj.properties.some((p) => p.key === key));
    fields.push(`${propertyName(key)}${optional ? "?" : ""}: ${withNull(unionTypes(exprs, uses))}`);
  }
  return `{ ${fields.join("; ")} }`;
}

/** A union with `null` last; `any` when a member is unknown or `null` is all there is. */
function withNull(types: readonly string[]): string {
  if (types.includes("any")) return "any";
  const known = types.filter((t) => t !== "null");
  if (known.length === 0) return "any";
  const nullable = types.includes("null");
  const ordered = known.length === 1 && !nullable ? known : known.map(grouped);
  if (nullable) ordered.push("null");
  return ordered.join(" | ");
}

/** The handle a builtin factory returns (`$http(…)` → `HttpResource<unknown>`), or `any`. */
function resourceType(builtin: string, args: ReadonlyArray<Expression>, uses: Set<string>): string {
  const config = args[0]?.kind === "Object" ? args[0] : null;
  const field = (key: string): Expression | undefined => config?.properties.find((p) => !p.spread && p.key === key)?.value;
  const use = (type: string): string => {
    uses.add(type);
    return type;
  };
  if (RESOURCE_TYPES[builtin]) return `${use(RESOURCE_TYPES[builtin]!)}<unknown>`;
  if (builtin === "query") {
    // `infinite: {…}` accumulates pages; a config held in a variable could be either.
    if (config === null || config.properties.some((p) => p.spread)) return "any";
    const infinite = field("infinite");
    const off = infinite === undefined || (infinite.kind === "Literal" && (infinite.value === null || infinite.value === false));
    return off ? `${use("HttpResource")}<unknown>` : `${use("InfiniteQueryResource")}<unknown>`;
  }
  if (builtin === "form") {
    const values = field("values");
    const shape = values?.kind === "Object" ? valueType(values, uses) : "any";
    return shape.startsWith("{ ") ? `${use("FormHandle")}<${shape}>` : use("FormHandle");
  }
  if (builtin === "i18n") return use("I18nInstance");
  if (builtin === "theme") return use("ThemeHandle");
  return "any";
}

/**
 * A value the module writes to a binding: the expression it assigns;
 * `"unknown"` when the source does not state it (`$n += step`); or `"member"`
 * for a write through a member (`$user.name = null`, `$cart.items.push(row)`),
 * which the runtime applies to whatever the binding holds — it turns a string
 * atom into an object.
 */
type Written = Expression | "unknown" | "member";

/**
 * The type of an atom or `let` binding: its initializer's, widened by every
 * value the module writes to it anywhere (`$selected = null` in an action makes
 * `number | null`). A write through a member makes the binding `any`, and so
 * does a write whose type is unknown, except for a primitive initializer, which
 * is assumed to keep its kind — `$count = $count + 1` keeps `$count` a number.
 */
function bindingType(init: Expression, writes: readonly Written[], uses: Set<string>): string {
  // Probe with a scratch set: only the final type's resource names are imported.
  const initial = valueType(init, new Set());
  if (initial === "any") return "any";
  const primitive = PRIMITIVES.has(initial);
  const known: Expression[] = [init];
  for (const write of writes) {
    if (write === "member") return "any";
    if (write === "unknown" || valueType(write, new Set()) === "any") {
      if (!primitive) return "any";
      continue;
    }
    known.push(write);
  }
  return withNull(unionTypes(known, uses));
}

/** Stands for a write whose result is a number: `$n++`, `$n -= 1`. */
const NUMBER: Expression = { kind: "Literal", value: 0 };

/** Array methods that change the array they are called on. */
const MUTATORS = new Set(["push", "unshift", "splice", "fill", "copyWithin"]);

/** `$x` / `x` for a direct reference to a binding, else `null`. */
function bindingKey(expr: Expression | undefined): string | null {
  if (expr?.kind === "StateRef") return `$${expr.name}`;
  if (expr?.kind === "Identifier") return expr.name;
  return null;
}

/** The binding a member chain starts from — `$cart` for `$cart.items[0].qty` — else `null`. */
function rootKey(expr: Expression | undefined): string | null {
  let node = expr;
  while (node?.kind === "Member" || node?.kind === "MethodCall") node = node.object;
  return bindingKey(node);
}

/** What `target <op>= value` leaves in a directly assigned binding. */
function compoundValue(operator: unknown, value: Expression | undefined): Written {
  if (value === undefined) return "unknown";
  // `=` and the logical forms store `value` itself (when they store anything).
  if (operator === "=" || operator === "??=" || operator === "||=" || operator === "&&=") return value;
  // `+=` concatenates or adds: a string operand makes a string, anything else is unknown.
  if (operator === "+=") return valueType(value, new Set()) === "string" ? value : "unknown";
  return NUMBER;
}

/**
 * Every value written to each binding anywhere in the module (`$x` / `x`),
 * initializers included — the widening input of {@link bindingType}. A write
 * is an assignment (`$x = v`, also in a lambda body), a compound assignment or
 * `++` / `--`, and anything that changes the value through a member chain that
 * starts at the binding: a member assignment or `delete`, an array mutator,
 * `Object.assign`. Writes inside component bodies count too, even where they
 * declare a local of the same name: that only widens. A write through another
 * name for the same object is not seen — `for (const t of $todos) t.done = x`
 * changes `$todos`'s rows in place.
 */
function assignedValues(program: Program): Map<string, Written[]> {
  const out = new Map<string, Written[]>();
  const record = (key: string | null, value: Written): void => {
    if (key === null) return;
    const list = out.get(key) ?? [];
    list.push(value);
    out.set(key, list);
  };
  walk(program, ({ node }) => {
    switch (node.kind) {
      case "Assignment":
        record(node.isState ? `$${node.identifier}` : node.identifier, node.expression);
        break;
      case "BuiltinCall": {
        const [target, value, op] = node.arguments;
        if (node.name === "__rui_assign__") {
          const direct = bindingKey(target);
          if (direct !== null) record(direct, compoundValue(op?.kind === "Literal" ? op.value : "=", value));
          else record(rootKey(target), "member");
        } else if (node.name === "__rui_prefix__" || node.name === "__rui_postfix__") {
          const direct = bindingKey(target);
          if (direct !== null) record(direct, NUMBER);
          else record(rootKey(target), "member");
        }
        break;
      }
      case "Unary":
        if (node.operator === "delete" && node.argument.kind === "Member") record(rootKey(node.argument), "member");
        break;
      case "MethodCall":
        if (MUTATORS.has(node.method)) record(rootKey(node.object), "member");
        if (node.object.kind === "Identifier" && node.object.name === "Object" && node.method === "assign") {
          record(rootKey(node.arguments[0]), "member");
        }
        break;
      default:
        break;
    }
  });
  return out;
}

