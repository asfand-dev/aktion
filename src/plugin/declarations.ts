/** A glob (`src/**\/*.aktion`) as an anchored RegExp over `/`-separated relative paths. */
function globToRegExp(glob: string): RegExp {
  let re = "";
  for (let i = 0; i < glob.length; i += 1) {
    const ch = glob[i]!;
    if (ch === "*") {
      if (glob[i + 1] === "*") {
        const slash = glob[i + 2] === "/";
        re += slash ? "(?:.*/)?" : ".*";
        i += slash ? 2 : 1;
      } else {
        re += "[^/]*";
      }
    } else if (ch === "?") {
      re += "[^/]";
    } else {
      re += /[\\^$.|+()[\]{}]/.test(ch) ? `\\${ch}` : ch;
    }
  }
  return new RegExp(`^${re}$`);
}

const toPosix = (p: string): string => p.split(sep).join("/");

function walkFiles(dir: string, skip: ReadonlySet<string>, out: string[]): void {
  let entries: string[];
  try {
    entries = readdirSync(dir);
  } catch {
    return;
  }
  for (const name of entries) {
    const full = join(dir, name);
    if (skip.has(full)) continue;
    let stats;
    try {
      stats = statSync(full);
    } catch {
      continue;
    }
    if (stats.isDirectory()) {
      if (!SKIPPED_DIRECTORIES.has(name)) walkFiles(full, skip, out);
    } else if (stats.isFile()) {
      out.push(full);
    }
  }
}

/** True when `path` is `dir` or underneath it. */
function isInside(path: string, dir: string): boolean {
  const rel = relative(dir, path);
  return rel === "" || (!rel.startsWith("..") && !isAbsolute(rel));
}

interface Resolved {
  root: string;
  outDir: string;
  include: RegExp[];
  exclude: RegExp[];
  /** Alias targets and the directory each is mirrored into. */
  aliases: Array<{ target: string; mirror: string }>;
  write: boolean;
  warnings: string[];
}

function resolveOptions(options: AktionDeclarationsOptions): Resolved {
  const root = resolve(options.root ?? process.cwd());
  const outDir = resolve(root, options.outDir ?? DEFAULT_DECLARATIONS_DIR);
  const include = options.include ?? ["src/**/*.aktion"];
  const warnings: string[] = [];
  for (const glob of include) {
    if (glob.startsWith("../") || glob.startsWith("/") || isAbsolute(glob)) {
      warnings.push(
        `include "${glob}" matches nothing: globs are relative to the root (${root}) and cannot leave it. ` +
          "Declare a shared library through `alias` (aktion.config.json), or run aktion-dts with --root in the library.",
      );
    }
  }
  // Mirrored aliases need a directory of their own, even when each module's
  // declaration sits next to it.
  const mirrorRoot = outDir === root ? join(root, DEFAULT_DECLARATIONS_DIR) : outDir;
  const aliases: Resolved["aliases"] = [];
  for (const [prefix, target] of Object.entries(options.alias ?? {})) {
    const segments = prefix.replace(/\/+$/, "").split("/");
    if (isAbsolute(prefix) || segments.some((s) => s === "" || s === "." || s === "..")) {
      warnings.push(`alias "${prefix}" cannot be mirrored as a directory; its modules are not declared.`);
      continue;
    }
    aliases.push({ target: resolve(root, target), mirror: join(mirrorRoot, ...segments) });
  }
  return {
    root,
    outDir,
    include: include.map(globToRegExp),
    exclude: (options.exclude ?? []).map(globToRegExp),
    aliases,
    write: options.write !== false,
    warnings,
  };
}

const isModule = (file: string): boolean => /\.aktion$/i.test(file);
const excluded = (file: string, o: Resolved): boolean => o.exclude.some((re) => re.test(toPosix(relative(o.root, file))));

function isDeclared(file: string, o: Resolved): boolean {
  if (!isModule(file)) return false;
  const rel = toPosix(relative(o.root, file));
  if (rel.startsWith("..")) return false;
  return o.include.some((re) => re.test(rel)) && !excluded(file, o);
}

/** Every declaration a module gets: under `outDir` when `include` matches it, and in each alias mirror it sits in. */
function targetsOf(file: string, o: Resolved): string[] {
  const targets: string[] = [];
  if (isDeclared(file, o)) targets.push(join(o.outDir, declarationFileName(relative(o.root, file))));
  if (isModule(file) && !excluded(file, o)) {
    for (const { target, mirror } of o.aliases) {
      if (isInside(file, target)) targets.push(join(mirror, declarationFileName(relative(target, file))));
    }
  }
  return targets;
}

function emitOne(file: string, target: string, o: Resolved, result: AktionDeclarationsResult): void {
  const { text, errors } = aktionDeclarationText(readFileSync(file, "utf8"), toPosix(relative(o.root, file)));
  for (const e of errors) {
    if (!result.diagnostics.some((d) => d.path === file && d.line === e.line && d.column === e.column && d.message === e.message)) {
      result.diagnostics.push({ path: file, line: e.line, column: e.column, message: e.message });
    }
  }
  const current = existsSync(target) ? readFileSync(target, "utf8") : null;
  if (current === text) {
    result.unchanged.push(target);
  } else {
    result.written.push(target);
    if (o.write) {
      mkdirSync(dirname(target), { recursive: true });
      writeFileSync(target, text);
    }
  }
}

/** True when `file` is a declaration this module generated (its first line says so). */
function isGenerated(file: string): boolean {
  if (!file.endsWith(".d.aktion.ts")) return false;
  try {
    return readFileSync(file, "utf8").slice(0, DECLARATION_HEADER.length) === DECLARATION_HEADER;
  } catch {
    return false;
  }
}

/**
 * Write a `name.d.aktion.ts` declaration for every `.aktion` module under
 * `root` that `include` matches, and for every module under an `alias` target
 * — only where the text changed, so a watcher does not fire for nothing — and
 * remove generated declarations whose module is gone.
 */
export function emitAktionDeclarations(options: AktionDeclarationsOptions = {}): AktionDeclarationsResult {
  const o = resolveOptions(options);
  const result: AktionDeclarationsResult = { written: [], unchanged: [], removed: [], diagnostics: [], warnings: [...o.warnings] };
  const files: string[] = [];
  walkFiles(o.root, new Set([o.outDir]), files);
  for (const { target } of o.aliases) if (!isInside(target, o.root)) walkFiles(target, new Set(), files);
  const targets = new Set<string>();
  for (const file of [...new Set(files)].sort()) {
    for (const target of targetsOf(file, o)) {
      if (targets.has(target)) continue;
      targets.add(target);
      emitOne(file, target, o, result);
    }
  }

  // Stale declarations: generated by us (the header says so), module gone.
  const existing: string[] = [];
  walkFiles(o.outDir === o.root ? o.root : o.outDir, new Set(), existing);
  for (const file of existing) {
    if (targets.has(file) || !isGenerated(file)) continue;
    result.removed.push(file);
    if (o.write) rmSync(file, { force: true });
  }
  return result;
}

/**
 * Bring one module's declarations up to date — after an edit, or remove them
 * after a deletion. Used by the Vite plugin's dev server; a module neither
 * `include` nor an `alias` target covers is ignored.
 */
export function updateAktionDeclaration(file: string, options: AktionDeclarationsOptions = {}): AktionDeclarationsResult {
  const o = resolveOptions(options);
  const result: AktionDeclarationsResult = { written: [], unchanged: [], removed: [], diagnostics: [], warnings: [] };
  const absolute = resolve(file);
  for (const target of targetsOf(absolute, o)) {
    if (existsSync(absolute)) {
      emitOne(absolute, target, o, result);
    } else if (existsSync(target)) {
      result.removed.push(target);
      if (o.write) rmSync(target, { force: true });
    }
  }
  return result;
}
