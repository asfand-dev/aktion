#!/usr/bin/env node
/**
 * Generate `docs/assets/live-example.js` from the per-example HTML files in
 * `docs/_examples/`.
 *
 * Each example in `_examples/` is a self-contained author-facing source: it
 * carries the example's title, description, source code blocks, and a setup
 * `<script type="module">` that wires `setTools()` and `setResponse()`.
 *
 * The shipped site only loads ONE shell page (`live-example.html`) + ONE JS
 * bundle (`assets/live-example.js`). The shell creates the same DOM structure
 * each `_examples/` page used to render (cards with `<code id="src-…">` blocks
 * and `<streaming-ui-script id="rui-…">` elements), so the setup scripts can
 * run unchanged against the dynamically-built layout.
 */

import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const sourcesDir = resolve(root, "docs/_examples");
const outFile = resolve(root, "docs/assets/live-example.js");

const HEADER = `/**
 * AUTO-GENERATED by scripts/build-live-examples.mjs — do not hand-edit.
 *
 * Source of truth: docs/_examples/<slug>.html. Run \`npm run build:examples\`
 * after editing any of those files.
 *
 * The shell page (docs/live-example.html) loads this single module to render
 * any of the bundled live examples on demand via the \`?example=<slug>\` query
 * parameter. Each example's setup script keeps the original
 * \`document.getElementById("rui-<id>")\` / \`document.getElementById("src-<id>")\`
 * references; the bootstrapper builds the matching DOM before the setup runs.
 */
`;

function extract(re, source, label) {
  const match = source.match(re);
  if (!match) throw new Error(`Could not extract ${label}`);
  return match[1];
}

function tryExtract(re, source) {
  const match = source.match(re);
  return match ? match[1] : null;
}

function extractAll(re, source) {
  const flags = re.flags.includes("g") ? re.flags : `${re.flags}g`;
  const global = new RegExp(re.source, flags);
  const out = [];
  let m;
  while ((m = global.exec(source))) out.push(m);
  return out;
}

function parseExample(slug, html) {
  const titleMatch = tryExtract(/<title>([^<]+)<\/title>/, html);
  const docTitle = titleMatch ? titleMatch.trim() : slug;

  const heroBlock = extract(
    /<section class="example-hero">([\s\S]*?)<\/section>/,
    html,
    `hero in ${slug}`,
  );
  const eyebrow = (
    tryExtract(/<span class="tag-pill">([\s\S]*?)<\/span>/, heroBlock) ?? ""
  ).trim();
  const heroTitleHtml = (
    tryExtract(/<h1[^>]*>([\s\S]*?)<\/h1>/, heroBlock) ?? ""
  ).trim();
  const heroDescriptionHtml = (
    tryExtract(/<p>([\s\S]*?)<\/p>/, heroBlock) ?? ""
  ).trim();

  const brandHref =
    tryExtract(/<a class="example-brand"\s+href="([^"]+)"/, html) ??
    "live-examples.html";
  const backHref =
    tryExtract(/<a class="example-back"\s+href="([^"]+)"/, html) ??
    "live-examples.html";
  const brandText = (
    tryExtract(
      /<a class="example-brand"[^>]*>[\s\S]*?<\/span>([\s\S]*?)<\/a>/,
      html,
    ) ?? `streaming-ui-script · ${slug}`
  ).trim();
  const backText = (
    tryExtract(/<a class="example-back"[^>]*>([\s\S]*?)<\/a>/, html) ??
    "← Back to live examples"
  ).trim();

  const cardMatches = extractAll(
    /<article class="example-card"([^>]*)>([\s\S]*?)<\/article>/g,
    html,
  );
  const cards = cardMatches.map(([, attrs, body]) => {
    const id = tryExtract(/id="([^"]+)"/, attrs);
    const heading = (
      tryExtract(/<h2[^>]*>([\s\S]*?)<\/h2>/, body) ?? ""
    ).trim();
    const lede = (
      tryExtract(/<p class="lede"[^>]*>([\s\S]*?)<\/p>/, body) ?? ""
    ).trim();

    const codeBlocks = extractAll(
      /<pre class="example-source"><code(?:\s+id="([^"]+)")?>([\s\S]*?)<\/code><\/pre>/g,
      body,
    ).map(([, codeId, content]) => ({ codeId: codeId ?? null, content }));

    const outputBlock = tryExtract(
      /<div class="example-output">([\s\S]*?)<\/div>/,
      body,
    );
    let render = null;
    if (outputBlock) {
      const elId = tryExtract(/id="([^"]+)"/, outputBlock);
      const theme = tryExtract(/theme="([^"]+)"/, outputBlock) ?? "light";
      if (elId) render = { elId, theme };
    }

    const extraHtml = (() => {
      let rest = body
        .replace(/<h2[^>]*>[\s\S]*?<\/h2>/, "")
        .replace(/<p class="lede"[^>]*>[\s\S]*?<\/p>/, "")
        .replace(
          /<pre class="example-source"><code(?:\s+id="[^"]+")?>[\s\S]*?<\/code><\/pre>/g,
          "",
        )
        .replace(/<div class="example-output">[\s\S]*?<\/div>/, "")
        .replace(/^\s+|\s+$/g, "");
      return rest;
    })();

    return {
      id: id ?? null,
      heading,
      lede,
      codeBlocks,
      render,
      extraHtml,
    };
  });

  const scriptBody = (() => {
    const blocks = extractAll(
      /<script type="module">([\s\S]*?)<\/script>/g,
      html,
    );
    const last = blocks[blocks.length - 1];
    if (!last) return "";
    return last[1]
      .replace(/^[\s\n]*import\s+["']\.\.\/dist\/streaming-ui-script\.js["'];?\s*\n?/m, "")
      .trim();
  })();

  return {
    slug,
    docTitle,
    eyebrow,
    heroTitleHtml,
    heroDescriptionHtml,
    brandHref,
    brandText,
    backHref,
    backText,
    cards,
    scriptBody,
  };
}

function escapeForBacktick(text) {
  return text.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
}

function asBacktickLiteral(text) {
  if (text == null) return "``";
  return `\`${escapeForBacktick(text)}\``;
}

function renderExampleObject(ex) {
  const cardLines = ex.cards.map((c) => {
    const codeBlocks = c.codeBlocks
      .map(
        (cb) =>
          `      { codeId: ${cb.codeId ? JSON.stringify(cb.codeId) : "null"}, content: ${asBacktickLiteral(cb.content)} }`,
      )
      .join(",\n");
    const renderJson = c.render
      ? `{ elId: ${JSON.stringify(c.render.elId)}, theme: ${JSON.stringify(c.render.theme)} }`
      : "null";
    return [
      `    {`,
      `      id: ${c.id ? JSON.stringify(c.id) : "null"},`,
      `      heading: ${asBacktickLiteral(c.heading)},`,
      `      lede: ${asBacktickLiteral(c.lede)},`,
      `      codeBlocks: [\n${codeBlocks}${codeBlocks ? "\n      " : "      "}],`,
      `      render: ${renderJson},`,
      `      extraHtml: ${asBacktickLiteral(c.extraHtml)},`,
      `    }`,
    ].join("\n");
  });

  return [
    `  ${JSON.stringify(ex.slug)}: {`,
    `    slug: ${JSON.stringify(ex.slug)},`,
    `    docTitle: ${asBacktickLiteral(ex.docTitle)},`,
    `    eyebrow: ${asBacktickLiteral(ex.eyebrow)},`,
    `    heroTitleHtml: ${asBacktickLiteral(ex.heroTitleHtml)},`,
    `    heroDescriptionHtml: ${asBacktickLiteral(ex.heroDescriptionHtml)},`,
    `    brandHref: ${JSON.stringify(ex.brandHref)},`,
    `    brandText: ${asBacktickLiteral(ex.brandText)},`,
    `    backHref: ${JSON.stringify(ex.backHref)},`,
    `    backText: ${asBacktickLiteral(ex.backText)},`,
    `    cards: [\n${cardLines.join(",\n")}\n    ],`,
    `    setup(){`,
    ex.scriptBody,
    `    }`,
    `  }`,
  ].join("\n");
}

const RUNTIME = `
import "../../dist/streaming-ui-script.js";

const root = document.getElementById("example-root");
const params = new URLSearchParams(window.location.search);
const slug = params.get("example") || "tools-example";
const example = EXAMPLES[slug];

if (!example) {
  document.title = "Example not found · streaming-ui-script";
  root.innerHTML = renderNotFound(slug);
} else {
  document.title = example.docTitle;
  root.innerHTML = renderShell(example);
  customElements
    .whenDefined("streaming-ui-script")
    .then(() => {
      try {
        example.setup();
      } catch (err) {
        console.error("Live example setup failed:", err);
      }
    });
}

function renderNotFound(badSlug) {
  const known = Object.keys(EXAMPLES).sort().map((k) => \`<li><a href="?example=\${k}">\${k}</a></li>\`).join("");
  return \`
    <header class="example-topbar">
      <a class="example-brand" href="live-examples.html">
        <span class="dot"></span>
        streaming-ui-script · live example
      </a>
      <a class="example-back" href="live-examples.html">← Back to live examples</a>
    </header>
    <section class="example-hero">
      <span class="tag-pill">Not found</span>
      <h1 style="margin-top:10px">No example named "\${escapeHtml(badSlug)}"</h1>
      <p>Pick one of the bundled examples below, or head back to the catalog.</p>
    </section>
    <article class="example-card">
      <h2>Bundled examples</h2>
      <ul>\${known}</ul>
    </article>
  \`;
}

function renderShell(ex) {
  const cardsHtml = ex.cards.map(renderCard).join("");
  return \`
    <header class="example-topbar">
      <a class="example-brand" href="\${ex.brandHref}">
        <span class="dot"></span>\${ex.brandText}
      </a>
      <a class="example-back" href="\${ex.backHref}">\${ex.backText}</a>
    </header>

    <section class="example-hero">
      <span class="tag-pill">\${ex.eyebrow}</span>
      <h1 style="margin-top:10px">\${ex.heroTitleHtml}</h1>
      <p>\${ex.heroDescriptionHtml}</p>
    </section>

    \${cardsHtml}
  \`;
}

function renderCard(card) {
  const idAttr = card.id ? \` id="\${card.id}"\` : "";
  const heading = card.heading ? \`<h2>\${card.heading}</h2>\` : "";
  const lede = card.lede ? \`<p class="lede">\${card.lede}</p>\` : "";
  const codeBlocks = card.codeBlocks
    .map((cb) => {
      const idAttr = cb.codeId ? \` id="\${cb.codeId}"\` : "";
      return \`<pre class="example-source"><code\${idAttr}>\${cb.content}</code></pre>\`;
    })
    .join("");
  const output = card.render
    ? \`<div class="example-output"><streaming-ui-script id="\${card.render.elId}" theme="\${card.render.theme}"></streaming-ui-script></div>\`
    : "";
  const extra = card.extraHtml || "";
  return \`<article class="example-card"\${idAttr}>\${heading}\${lede}\${codeBlocks}\${output}\${extra}</article>\`;
}

function escapeHtml(text) {
  return String(text)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}
`;

async function main() {
  const files = (await readdir(sourcesDir)).filter((f) => f.endsWith(".html")).sort();
  if (files.length === 0) {
    throw new Error(`No HTML files found in ${sourcesDir}`);
  }

  const examples = [];
  for (const file of files) {
    const slug = file.replace(/\.html$/, "");
    const html = await readFile(resolve(sourcesDir, file), "utf8");
    try {
      examples.push(parseExample(slug, html));
    } catch (err) {
      throw new Error(`Failed to parse ${file}: ${err.message}`);
    }
  }

  const body = `${HEADER}\nconst EXAMPLES = {\n${examples.map(renderExampleObject).join(",\n")}\n};\n${RUNTIME}`;

  await writeFile(outFile, body, "utf8");
  console.log(
    `Wrote ${outFile} (${examples.length} examples, ${(body.length / 1024).toFixed(1)} KB)`,
  );
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
